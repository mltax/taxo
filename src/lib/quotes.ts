/** KST 기준 연중 일수(1~366)와 표시용 라벨 */
export function kstDate(now: Date = new Date()): {
  label: string;
  dayOfYear: number;
} {
  const ymd = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
  const [y, m, d] = ymd.split("-").map(Number);
  const dayOfYear = Math.floor(
    (Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 0)) / 86400000
  );
  const label = new Intl.DateTimeFormat("ko-KR", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "long",
    day: "numeric",
    weekday: "long",
  }).format(now);
  return { label, dayOfYear };
}

/**
 * 연중 일수에 코프라임(167) 순열을 적용해 1년간 중복 없이 매일 다른 명언을 반환.
 * (QUOTES 길이와 무관하게 동작하며, 365개 이상이면 1년 내 비반복이 보장된다.)
 */
export function dailyQuote(now: Date = new Date()): Quote {
  const n = QUOTES.length;
  const { dayOfYear } = kstDate(now);
  const idx = ((dayOfYear * 167) % n + n) % n;
  return QUOTES[idx];
}
